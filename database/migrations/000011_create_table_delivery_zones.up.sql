create table
    public.delivery_zones (
                     id bigint generated by default as identity not null,
                     shop_delivery_method_id bigint not null,
                     name text not null,
                     price decimal(10,2) not null,
                     created_at timestamp with time zone not null default now(),
                     constraint delivery_zones_pkey primary key (id),
                     constraint delivery_zones_sdm_id_fkey foreign key (shop_delivery_method_id) references shop_delivery_methods (id) on update cascade on delete cascade
) tablespace pg_default;

CREATE INDEX IF NOT EXISTS idx_delivery_zones_sdm_id ON public.delivery_zones (shop_delivery_method_id);
