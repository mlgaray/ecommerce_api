-- ============================================================================
-- TABLE: orders
-- Orden principal del sistema de e-commerce
-- ============================================================================
CREATE TABLE public.orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,

    -- Número de orden legible (secuencial por store)
    order_number text NOT NULL,

    -- Store (FK requerida, apunta a shops.id)
    store_id bigint NOT NULL,
    store_name text NOT NULL,
    store_slug text NOT NULL,

    -- Estado
    status text NOT NULL DEFAULT 'pending',

    -- Cliente (embebido, incluye dirección de entrega)
    customer_name text NOT NULL,
    customer_phone text NULL,
    customer_email text NULL,
    customer_address_name text NULL,
    customer_address_place_id text NULL,
    customer_address_lat double precision NULL,
    customer_address_lng double precision NULL,

    -- Método de pago (snapshot)
    payment_method_id bigint NULL,
    payment_method_code text NULL,
    payment_method_name text NULL,

    -- Método de entrega (snapshot)
    delivery_method_id bigint NULL,
    delivery_method_code text NULL,
    delivery_method_name text NULL,

    -- Zona de entrega (snapshot)
    delivery_zone_id bigint NULL,
    delivery_zone_name text NULL,
    delivery_zone_price double precision NULL,

    -- Totales
    subtotal double precision NOT NULL DEFAULT 0,
    shipping_cost double precision NOT NULL DEFAULT 0,
    discount double precision NOT NULL DEFAULT 0,
    total double precision NOT NULL DEFAULT 0,

    -- Cupón (snapshot al momento de la orden)
    coupon_code text NULL,
    coupon_type text NULL,
    coupon_value double precision NULL,
    coupon_discount_amount double precision NULL,
    coupon_min_order_amount double precision NULL,

    -- Timestamps
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),

    -- Constraints
    CONSTRAINT orders_pkey PRIMARY KEY (id),
    CONSTRAINT orders_store_id_fkey FOREIGN KEY (store_id)
        REFERENCES shops (id) ON DELETE RESTRICT,
    CONSTRAINT orders_payment_method_id_fkey FOREIGN KEY (payment_method_id)
        REFERENCES payment_methods (id) ON DELETE SET NULL,
    CONSTRAINT orders_delivery_method_id_fkey FOREIGN KEY (delivery_method_id)
        REFERENCES delivery_methods (id) ON DELETE SET NULL,
    CONSTRAINT orders_delivery_zone_id_fkey FOREIGN KEY (delivery_zone_id)
        REFERENCES delivery_zones (id) ON DELETE SET NULL,
    CONSTRAINT orders_status_check CHECK (
        status IN ('pending', 'confirmed', 'completed', 'cancelled')
    ),
    CONSTRAINT orders_coupon_type_check CHECK (
        coupon_type IS NULL OR coupon_type IN ('percentage', 'fixed')
    ),
    CONSTRAINT orders_order_number_store_unique UNIQUE (store_id, order_number)
) TABLESPACE pg_default;

-- ============================================================================
-- INDEXES: Optimizados para métricas y consultas frecuentes
-- ============================================================================

-- Listado de órdenes por store
CREATE INDEX idx_orders_store_id ON public.orders (store_id);

-- Filtrado por estado
CREATE INDEX idx_orders_status ON public.orders (status);

-- Métricas de ventas por período
CREATE INDEX idx_orders_store_created_at ON public.orders (store_id, created_at DESC);

-- Dashboard: órdenes por store y estado ordenadas por fecha
CREATE INDEX idx_orders_store_status_created ON public.orders (store_id, status, created_at DESC);

-- Métricas por método de pago
CREATE INDEX idx_orders_payment_method_id ON public.orders (payment_method_id);

-- Métricas por método de entrega
CREATE INDEX idx_orders_delivery_method_id ON public.orders (delivery_method_id);

-- Búsqueda por cliente (email)
CREATE INDEX idx_orders_customer_email ON public.orders (customer_email)
    WHERE customer_email IS NOT NULL;

-- Search by order number (customer support, tracking)
CREATE INDEX idx_orders_order_number ON public.orders (order_number);

-- Search by customer phone
CREATE INDEX idx_orders_customer_phone ON public.orders (customer_phone)
    WHERE customer_phone IS NOT NULL;

-- Dashboard: pending orders requiring attention (partial index)
CREATE INDEX idx_orders_store_pending ON public.orders (store_id, created_at DESC)
    WHERE status IN ('pending', 'confirmed');

-- Date range queries without store filter (admin reports)
CREATE INDEX idx_orders_created_at ON public.orders (created_at DESC);

-- Completed orders for revenue reports (partial index)
CREATE INDEX idx_orders_store_completed ON public.orders (store_id, created_at DESC)
    WHERE status = 'completed';

-- Trigram indexes for fast ILIKE search (order_number and customer_name)
CREATE INDEX idx_orders_order_number_trgm ON public.orders USING gin (order_number gin_trgm_ops);
CREATE INDEX idx_orders_customer_name_trgm ON public.orders USING gin (customer_name gin_trgm_ops);

-- Comentarios de documentación
COMMENT ON TABLE orders IS 'Órdenes del sistema. Contiene snapshots desnormalizados de store, cliente, dirección y métodos para preservar datos históricos.';
COMMENT ON COLUMN orders.status IS 'Estados: pending (pendiente), confirmed (confirmada), completed (completada), cancelled (cancelada)';
COMMENT ON COLUMN orders.subtotal IS 'Suma de order_items.total_price. Calculado y almacenado para performance.';
COMMENT ON COLUMN orders.discount IS 'Monto de descuento aplicado por cupón. 0 si no hay cupón.';
COMMENT ON COLUMN orders.total IS 'subtotal - discount + shipping_cost. Almacenado para evitar recálculos.';
COMMENT ON COLUMN orders.delivery_zone_id IS 'Snapshot: ID de la zona de entrega seleccionada. NULL si el metodo no usa zonas o si la zona fue eliminada.';
COMMENT ON COLUMN orders.delivery_zone_name IS 'Snapshot: Nombre de la zona al momento de la orden. Preserva dato historico.';
COMMENT ON COLUMN orders.delivery_zone_price IS 'Snapshot: Precio de la zona al momento de la orden. Preserva dato historico.';

-- Enable Row Level Security
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;
