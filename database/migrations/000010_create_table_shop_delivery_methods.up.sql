create table
    public.shop_delivery_methods (
                     id bigint generated by default as identity not null,
                     shop_id bigint not null,
                     delivery_method_id bigint not null,
                     is_active boolean not null default true,
                     created_at timestamp with time zone not null default now(),
                     constraint shop_delivery_methods_pkey primary key (id),
                     constraint shop_delivery_methods_shop_delivery_unique unique (shop_id, delivery_method_id),
                     constraint shop_delivery_methods_shop_id_fkey foreign key (shop_id) references shops (id) on update cascade on delete cascade,
                     constraint shop_delivery_methods_delivery_method_id_fkey foreign key (delivery_method_id) references delivery_methods (id) on update cascade on delete restrict
) tablespace pg_default;

CREATE INDEX IF NOT EXISTS idx_shop_delivery_methods_shop_id ON public.shop_delivery_methods (shop_id);
CREATE INDEX IF NOT EXISTS idx_shop_delivery_methods_delivery_method_id ON public.shop_delivery_methods (delivery_method_id);
CREATE INDEX IF NOT EXISTS idx_shop_delivery_methods_is_active ON public.shop_delivery_methods (is_active);
