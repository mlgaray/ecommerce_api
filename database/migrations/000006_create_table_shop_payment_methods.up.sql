create table
    public.shop_payment_methods (
                     id bigint generated by default as identity not null,
                     shop_id bigint not null,
                     payment_method_id bigint not null,
                     is_active boolean not null default true,
                     created_at timestamp with time zone not null default now(),
                     constraint shop_payment_methods_pkey primary key (id),
                     constraint shop_payment_methods_shop_payment_unique unique (shop_id, payment_method_id),
                     constraint shop_payment_methods_shop_id_fkey foreign key (shop_id) references shops (id) on update cascade on delete cascade,
                     constraint shop_payment_methods_payment_method_id_fkey foreign key (payment_method_id) references payment_methods (id) on update cascade on delete restrict
) tablespace pg_default;

CREATE INDEX IF NOT EXISTS idx_shop_payment_methods_shop_id ON public.shop_payment_methods (shop_id);
CREATE INDEX IF NOT EXISTS idx_shop_payment_methods_payment_method_id ON public.shop_payment_methods (payment_method_id);
CREATE INDEX IF NOT EXISTS idx_shop_payment_methods_is_active ON public.shop_payment_methods (is_active);

-- Enable Row Level Security (blocks REST API access without policies)
ALTER TABLE shop_payment_methods ENABLE ROW LEVEL SECURITY;
