-- ============================================================================
-- TABLE: coupons
-- Cupones de descuento por tienda
-- ============================================================================
CREATE TABLE public.coupons (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,

    -- Store (FK requerida)
    shop_id bigint NOT NULL,

    -- Datos del cupón
    code text NOT NULL,
    type text NOT NULL,
    value double precision NOT NULL,
    min_order_amount double precision NULL,
    usage_limit integer NULL,
    max_uses_per_phone integer NULL,

    -- Vigencia
    starts_at timestamp with time zone NULL,
    expires_at timestamp with time zone NULL,

    -- Estado
    is_active boolean NOT NULL DEFAULT true,

    -- Timestamps
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),

    -- Constraints
    CONSTRAINT coupons_pkey PRIMARY KEY (id),
    CONSTRAINT coupons_shop_id_fkey FOREIGN KEY (shop_id)
        REFERENCES shops (id) ON DELETE RESTRICT,
    CONSTRAINT coupons_code_shop_id_unique UNIQUE (code, shop_id),
    CONSTRAINT coupons_type_check CHECK (type IN ('percentage', 'fixed'))
) TABLESPACE pg_default;

-- Indexes
CREATE INDEX idx_coupons_shop_id ON public.coupons (shop_id);
CREATE INDEX idx_coupons_code ON public.coupons (code);

-- Comments
COMMENT ON TABLE coupons IS 'Cupones de descuento por tienda. Cada cupón pertenece a un shop y tiene un código único por shop.';
COMMENT ON COLUMN coupons.type IS 'Tipo de descuento: percentage (porcentaje) o fixed (monto fijo)';
COMMENT ON COLUMN coupons.value IS 'Valor del descuento: porcentaje (0-100) o monto fijo';
COMMENT ON COLUMN coupons.usage_limit IS 'Límite global de usos del cupón. NULL = sin límite';
COMMENT ON COLUMN coupons.max_uses_per_phone IS 'Máximo de usos por teléfono. NULL = sin límite por teléfono';

-- Enable Row Level Security
ALTER TABLE coupons ENABLE ROW LEVEL SECURITY;
